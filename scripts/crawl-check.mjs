// Moz crawl issues we can catch before they ship. Run after `npm run build`:
// `npm run check:crawl`.
//
//   missing canonical     an indexable page with no <link rel="canonical">
//   has meta noindex      any page other than the allowlist below
//   title too long        rendered <title> wider than ~600px (Moz's cutoff)
//   description too short meta description under 55 characters (Moz's cutoff)
//   thin content          indexable HTML authored in public/ with under 250 words
//                         outside <script>, <style>, and <svg>
//   genome pages          every compiled genome has its /playground/<key>/ page, its card on
//                         /operating-model-template, a 1200 × 628 share card, og:image and
//                         twitter:image, a sitemap entry and an /llms.txt entry; the homepage
//                         hero's second action is still the Playground
//
// public/agents/ is generated by dna-codes-platform and is not edited here, so it
// is skipped. The CMS admin at /decapcms/ is the one page allowed to be noindex.

import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join, dirname, resolve, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const publicDir = join(root, 'public');
const TITLE_LIMIT_PX = 600;
const THIN_WORDS = 250;
const DESCRIPTION_MIN = 55; // Moz "Description Too Short"
const SKIP_DIRS = new Set(['agents', '_astro']);

// Unscaled Arial-ish advances, then × SCALE so the samples from the 2026-11-09
// Moz export land within about 20px of the pixel length Moz reported. The gate
// stays at Moz's 600. Keep titles under ~560 so that error still clears it.
const SCALE = 1.22;
const WIDTH = {
  ' ': 4.45,
  "'": 3.1,
  ',': 4.4,
  '-': 5.3,
  '.': 4.4,
  ':': 4.4,
  ';': 4.4,
  '?': 8.9,
  I: 4.5,
  J: 8,
  W: 15.2,
  i: 3.6,
  j: 3.6,
  l: 3.6,
  f: 4.5,
  t: 4.5,
  r: 5.3,
  m: 13.4,
  w: 11.6,
  '—': 15.2,
  '–': 8.9,
  '’': 3.1,
};

if (!existsSync(join(dist, 'index.html'))) {
  console.error('crawl-check: dist/index.html not found. Run `npm run build` first.');
  process.exit(1);
}

const failures = [];
const fail = (check, detail) => failures.push({ check, detail });

const htmlFiles = [];
(function walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (dir === dist && SKIP_DIRS.has(entry.name)) continue;
      walk(p);
    } else if (entry.name.endsWith('.html')) htmlFiles.push(p);
  }
})(dist);

const attr = (tag, name) => tag.match(new RegExp(`\\b${name}=["']?([^"'\\s>]+)`, 'i'))?.[1];
const routeOf = (file) =>
  '/' +
  relative(dist, file)
    .split(sep)
    .join('/')
    .replace(/(^|\/)index\.html$/, '')
    .replace(/\.html$/, '');

const decode = (value) =>
  value
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;|&#0?39;/g, "'")
    .replace(/&mdash;|&#8212;/g, '—')
    .replace(/&ndash;|&#8211;/g, '–')
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/\s+/g, ' ')
    .trim();

const titleOf = (html) => decode(html.match(/<title[^>]*>([\s\S]*?)<\/title>/i)?.[1] ?? '');

const titlePixels = (title) => Math.round([...title].reduce((n, ch) => n + (WIDTH[ch] ?? 9), 0) * SCALE);

const robotsContent = (html) => {
  for (const tag of html.match(/<meta\b[^>]*>/gi) ?? []) {
    const name = (attr(tag, 'name') || '').toLowerCase();
    if (name === 'robots' || name === 'googlebot') return (attr(tag, 'content') || '').toLowerCase();
  }
  return '';
};

// Page 2+ of the blog, a tag, or a category is an archive slice. The list route
// already marks those noindex. Tag page 1 (/tag/bpmn) does not match.
const paginatedArchive = (route) => /^\/(?:blog|tag\/[^/]+|category\/[^/]+)\/\d+$/.test(route);
const noindexAllowed = (route) => route === '/decapcms' || route.startsWith('/decapcms/') || paginatedArchive(route);

const bodyWords = (html) => {
  const text = html
    .replace(/<script\b[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style\b[\s\S]*?<\/style>/gi, ' ')
    .replace(/<svg\b[\s\S]*?<\/svg>/gi, ' ')
    .replace(/<noscript\b[\s\S]*?<\/noscript>/gi, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&[a-z#0-9]+;/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  return text ? text.split(' ').filter(Boolean).length : 0;
};

let pages = 0;
for (const file of htmlFiles) {
  const html = readFileSync(file, 'utf8');
  if (/http-equiv=["']?refresh/i.test(html)) continue;
  pages++;
  const route = routeOf(file) || '/';
  const robots = robotsContent(html);
  const noindex = /\bnoindex\b/.test(robots);

  if (noindex && !noindexAllowed(route)) {
    fail('noindex', `${route} has meta noindex. Index it, or add it to the allowlist in scripts/crawl-check.mjs.`);
  }

  const indexable = !noindex;
  if (indexable && !/<link\b[^>]*rel=["']?canonical/i.test(html)) {
    fail('canonical', `${route} is indexable and has no canonical URL.`);
  }

  if (indexable) {
    const title = titleOf(html);
    const px = titlePixels(title);
    if (title && px > TITLE_LIMIT_PX) {
      fail('title', `${route} title is about ${px}px (limit ${TITLE_LIMIT_PX}): ${title}`);
    }

    const descTag = (html.match(/<meta\b[^>]*>/gi) ?? []).find((tag) => /\bname=["']?description\b/i.test(tag));
    const description = decode(
      descTag
        ?.match(/\bcontent=(?:"([^"]*)"|'([^']*)')/i)
        ?.slice(1)
        .find(Boolean) ?? ''
    );
    if (description.length < DESCRIPTION_MIN) {
      fail(
        'description',
        `${route} meta description is ${description.length} characters (needs ${DESCRIPTION_MIN}): ${description}`
      );
    }
  }

  const fromPublic = existsSync(join(publicDir, relative(dist, file)));
  if (indexable && fromPublic) {
    const words = bodyWords(html);
    if (words < THIN_WORDS) {
      fail(
        'thin-content',
        `${route} has ${words} words outside script and style (needs ${THIN_WORDS}). The copy has to be in the HTML body, not only in a script.`
      );
    }
  }
}

// --- Genome pages ---------------------------------------------------------------
//
// Every compiled genome the build emitted (/genome/<key>.json) must have its Playground page, its
// card on /operating-model-template, its share card, and og:image and twitter:image tags that
// point at that card. The homepage hero must still lead to the Playground.

const ORIGIN = 'https://dna.codes';
const genomeDir = join(dist, 'genome');
const genomeKeys = existsSync(genomeDir)
  ? readdirSync(genomeDir)
      .filter((name) => name.endsWith('.json'))
      .map((name) => name.replace(/\.json$/, ''))
  : [];

/** Width and height from a PNG's IHDR chunk. */
const pngSize = (file) => {
  const b = readFileSync(file);
  return { width: b.readUInt32BE(16), height: b.readUInt32BE(20) };
};
const metaContent = (html, property) => {
  for (const tag of html.match(/<meta\b[^>]*>/gi) ?? []) {
    if ((attr(tag, 'property') || attr(tag, 'name')) === property) return attr(tag, 'content');
  }
  return undefined;
};
const linksTo = (html, path, text) =>
  [...html.matchAll(/<a\b([^>]*)>([\s\S]*?)<\/a>/gi)].some(
    ([, attrs, inner]) =>
      (attr(`<a ${attrs}>`, 'href') || '').replace(/\/$/, '') === path.replace(/\/$/, '') &&
      (!text || decode(inner.replace(/<[^>]+>/g, ' ')) === text)
  );
const checkCard = (file, label) => {
  if (!existsSync(file)) return fail('genome', `${label} share card is missing.`);
  const { width, height } = pngSize(file);
  if (width !== 1200 || height !== 628) fail('genome', `${label} share card is ${width} × ${height}, not 1200 × 628.`);
};
const checkImages = (html, route, image) => {
  if (metaContent(html, 'og:image') !== image) fail('genome', `${route} og:image does not point at ${image}.`);
  if (metaContent(html, 'twitter:image') !== image)
    fail('genome', `${route} twitter:image does not point at ${image}.`);
};

if (!genomeKeys.length) fail('genome', 'dist/genome/ has no compiled genomes.');

const templateFile = join(dist, 'operating-model-template', 'index.html');
const template = existsSync(templateFile) ? readFileSync(templateFile, 'utf8') : '';
if (!template) fail('genome', '/operating-model-template/ was not built.');
else checkImages(template, '/operating-model-template/', `${ORIGIN}/operating-model-template.png`);
checkCard(join(dist, 'operating-model-template.png'), '/operating-model-template/');

const sitemap = readdirSync(dist)
  .filter((name) => /^sitemap.*\.xml$/.test(name))
  .map((name) => readFileSync(join(dist, name), 'utf8'))
  .join('\n');
const llms = existsSync(join(dist, 'llms.txt')) ? readFileSync(join(dist, 'llms.txt'), 'utf8') : '';
for (const route of ['/operating-model-template/', ...genomeKeys.map((key) => `/playground/${key}/`)]) {
  if (!sitemap.includes(`<loc>${ORIGIN}${route}</loc>`)) fail('genome', `${route} is not in the sitemap.`);
  if (!llms.includes(`(${ORIGIN}${route})`)) fail('genome', `${route} is not in /llms.txt.`);
}

for (const key of genomeKeys) {
  const route = `/playground/${key}/`;
  const page = join(dist, 'playground', key, 'index.html');
  if (!existsSync(page)) {
    fail('genome', `${route} was not built.`);
    continue;
  }
  checkCard(join(dist, 'playground', `${key}.png`), route);
  checkImages(readFileSync(page, 'utf8'), route, `${ORIGIN}/playground/${key}.png`);
  if (template && !linksTo(template, route)) fail('genome', `/operating-model-template/ has no card for ${key}.`);
}

const home = readFileSync(join(dist, 'index.html'), 'utf8');
const hero = home.match(/<h1\b[\s\S]*?<\/section>/i)?.[0] ?? '';
if (!linksTo(hero, '/playground/', 'Playground')) {
  fail('genome', 'The homepage hero no longer has its "Playground" action.');
}

if (failures.length) {
  console.error(`crawl-check: ${failures.length} problem(s) across ${pages} pages\n`);
  for (const { check, detail } of failures) console.error(`  ✗ [${check}] ${detail}`);
  console.error('\nThese are the Moz crawl issues this site has shipped before. See AGENTS.md, "Search crawl".');
  process.exit(1);
}

console.log(
  `crawl-check: ${pages} pages pass canonical, index, title width, description length, and thin content. ${genomeKeys.length} genomes have their Playground page, template card, and share card.`
);
